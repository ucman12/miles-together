"""Generate src/generated/sheets.h from the JSON sheets: one piece of code per row."""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHEETS = ROOT / "sheets"
OUT = ROOT / "src" / "generated" / "sheets.h"


def rows(name: str) -> list[dict]:
    return json.loads((SHEETS / f"{name}.json").read_text(encoding="utf-8"))["rows"]


def ident(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", text)


def cstr(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    out: list[str] = [
        "// GENERATED by tools/gen_sheets.py from sheets/*.json. Do not edit; change the sheet.",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace sheets {",
        "",
    ]

    comp = rows("compatibility")[0]
    out += [
        "// compatibility",
        "namespace compatibility {",
        f"inline constexpr const char* executable = {cstr(comp['executable'])};",
        f"inline constexpr std::uint32_t pe_timestamp = {comp['pe_timestamp']};",
        f"inline constexpr std::uint32_t size_of_image = {comp['size_of_image']};",
        f"inline constexpr const char* game_version = {cstr(comp['game_version'])};",
        "}",
        "",
        "// native_functions: one typed entry per row",
        "struct NativeFunction { const char* id; std::uint32_t rva; const std::uint8_t* signature; std::size_t signature_size; bool hook; };",
        "namespace fn {",
    ]
    table = []
    for row in rows("native_functions"):
        name = ident(row["id"])
        sig = bytes.fromhex(row["signature"])
        args = ", ".join(row["arguments"])
        out += [
            f"// {row['purpose']}",
            f"using {name}_t = {row['returns']} (*)({args});",
            f"inline constexpr std::uint32_t {name}_rva = {row['rva']};",
            f"inline constexpr std::uint8_t {name}_signature[] = {{{', '.join(f'0x{b:02x}' for b in sig)}}};",
        ]
        table.append(f"    {{{cstr(row['id'])}, fn::{name}_rva, fn::{name}_signature, sizeof(fn::{name}_signature), {'true' if row['kind'] == 'hook' else 'false'}}},")
    out += ["}", "inline constexpr NativeFunction native_functions[] = {", *table, "};", ""]

    out += ["// native_data", "namespace data {"]
    for row in rows("native_data"):
        out += [f"// {row['purpose']}", f"inline constexpr std::uint32_t {ident(row['id'])}_rva = {row['rva']};"]
    out += ["}", "", "// layout", "namespace layout {"]
    for row in rows("layout"):
        out += [f"// {row['purpose']}", f"inline constexpr std::uint32_t {ident(row['id'])} = {int(row['value'])};"]
    out += ["}", "", "// assets", "namespace assets {"]
    for row in rows("assets"):
        out += [f"// {row['path']}", f"inline constexpr std::uint64_t {ident(row['id'])} = {row['asset_id']}ull;"]
    out += ["}", "", "// net_messages", "enum class Message : std::uint8_t {"]
    for row in rows("net_messages"):
        out += [f"    {ident(row['id'])} = {int(row['code'])},  // {row['purpose']}"]
    out += ["};", "", "// settings", "namespace settings {"]
    for row in rows("settings"):
        out += [f"// {row['purpose']} ({row['unit']})", f"inline constexpr std::uint32_t {ident(row['id'])} = {int(row['value'])};"]
    out += ["}", "", "// melty_contract", "namespace melty {"]
    for row in rows("melty_contract"):
        out += [f"// {row['purpose']}", f"inline constexpr const char* {ident(row['id'])} = {cstr(row['value'])};"]
    out += ["}", "", "// test_checks", "namespace checks {"]
    for row in rows("test_checks"):
        out += [f"// passes when: {row['passes_when']}", f"inline constexpr const char* {ident(row['id'])} = {cstr(row['id'])};"]
    out += ["}", "", "// systems", "inline constexpr const char* systems[] = {"]
    for row in rows("systems"):
        out += [f"    {cstr(row['id'])},"]
    design = {row["id"]: row["value"] for row in rows("design")}
    out += [
        "};",
        "",
        "// design",
        "namespace design {",
        f"inline constexpr const char* title = {cstr(design['title'])};",
        f"inline constexpr std::uint32_t players = {int(design['players'])};",
        "}",
        "",
        "}  // namespace sheets",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"generated {OUT.relative_to(ROOT)}: {len(out)} lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
